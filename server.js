require('dotenv').config();
const express=require('express');
const path=require('path');
const dashboard=require('./api/dashboard');
const assets=require('./api/assets');
const app=express();
app.disable('x-powered-by');
app.get('/api/dashboard/:tag', (req,res)=>{req.query.tag=req.params.tag;return dashboard(req,res);});
app.get('/api/assets',assets);
app.use(express.static(path.join(__dirname,'public')));
app.listen(Number(process.env.PORT)||3000,'127.0.0.1',()=>console.log('BrawlStats Public: http://localhost:'+(process.env.PORT||3000)));
